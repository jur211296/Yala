/**
 * El ícono Lucide de un SF Symbol. Sin símbolo, o con uno que no está en la tabla ni sin «.fill» ni sin «.circle», el de
 * `respaldo` (por defecto, la etiqueta de la app).
 */
export function iconoLucide(sf: string | null | undefined, respaldo: string = SIMBOLO_POR_DEFECTO): LucideIcon {
  for (const nombre of candidatos(sf)) {
    const icono = propio(nombre);
    if (icono) return icono;
  }
  return propio(respaldo) ?? Tag;
}

/** Solo claves de la tabla: «constructor» o «tostring» darían una función heredada de `Object` y React no la pinta. */
function propio(nombre: string): LucideIcon | undefined {
  return Object.hasOwn(SIMBOLOS, nombre) ? SIMBOLOS[nombre] : undefined;
}

function candidatos(sf: string | null | undefined): string[] {
  if (!sf) return [];
  const sinFill = sf.replace(/\.fill$/, "");
  return [sf, sinFill, sinFill.replace(/\.circle$/, ""), `${sinFill}.fill`];
}

/** Un color guardado que la página puede poner en un `style`: «#RRGGBB». Lo demás, el respaldo. */
export function colorSeguro(hex: string | null | undefined, respaldo: string): string {
  return typeof hex === "string" && /^#[0-9A-Fa-f]{6}$/.test(hex) ? hex : respaldo;
}

