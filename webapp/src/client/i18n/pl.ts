/** Plural polaco: una forma para 1, otra para 2-4 (salvo 12-14) y otra para el resto. */
function plural(n: number, one: string, few: string, many: string): string {
  if (n === 1) return one;
  const d = n % 10;
  const c = n % 100;
  return d >= 2 && d <= 4 && (c < 12 || c > 14) ? few : many;
}

