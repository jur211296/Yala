export function getTranslation(lang: Language) {
  return translations[lang] || translations[defaultLang];
}

// Alias for compatibility
export const getTranslations = getTranslation;

export function detectLanguage(acceptLanguage: string | null): Language {
  if (!acceptLanguage) return defaultLang;
  const supportedLangs = Object.keys(languages) as Language[];
  const browserLangs = acceptLanguage.split(',').map(l => l.split(';')[0].trim().substring(0, 2));
  for (const browserLang of browserLangs) {
    if (supportedLangs.includes(browserLang as Language)) {
      return browserLang as Language;
    }
  }
  return defaultLang;
}
